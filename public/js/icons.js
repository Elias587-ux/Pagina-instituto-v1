/**
 * Devuelve el SVG de un ícono como string.
 * @param {string} name
 * @param {string} [className='icon']
 */
export function icon(name, className = 'icon') {
  const paths = PATHS[name];
  if (!paths) return '';
  return `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** Reemplaza cada <span data-icon="nombre"> vacío por su SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (!el.firstElementChild) el.innerHTML = icon(el.dataset.icon);
  });
}
